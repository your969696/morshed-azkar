export function getGreeting(t) {
  const h = new Date().getHours();
  if (h >= 4 && h < 6) return t.home.greeting_fajr;
  if (h >= 6 && h < 12) return t.home.greeting_morning;
  if (h >= 12 && h < 14) return t.home.greeting_noon;
  if (h >= 14 && h < 17) return t.home.greeting_asr;
  if (h >= 17 && h < 21) return t.home.greeting_evening;
  return t.home.greeting_night;
}

